import test from 'node:test';
import assert from 'node:assert/strict';
import { systemEvent, transcriptMessages, transcriptModel } from '../mobile-transcript.mjs';

const notification = result => `<task-notification>\n<task-id>ac7d</task-id>\n<tool-use-id>toolu_01</tool-use-id>\n<output-file>E:\\tmp\\ac7d.output</output-file>\n<status>completed</status>\n<summary>Agent "/code-review high" finished</summary>\n<note>A task-notification fires each time this agent stops.</note>\n<result>${result}</result>\n</task-notification>`;

test('CLI-injected turns become compact system events', () => {
  const review = systemEvent(notification('```json\n[{"file":"Runtime/GameHud.cs","line":266,"summary":"Stale cell action","failure_scenario":"Barracks A, then B"},{"summary":"Pressed class stays"}]\n```'), { kind: 'task-notification' });
  assert.deepEqual(review, { kind: 'agent', title: 'Agent "/code-review high" finished', status: 'completed', findings: [
    { summary: 'Stale cell action', file: 'Runtime/GameHud.cs', line: 266, detail: 'Barracks A, then B' }, { summary: 'Pressed class stays' },
  ] });
  const withSummary = systemEvent(notification('Two low-severity problems.\n\n```json\n[{"summary":"Hover cleared in two places","file":"GameHud.cs"}]\n```'));
  assert.deepEqual([withSummary.detail, withSummary.findings], ['Two low-severity problems.', [{ summary: 'Hover cleared in two places', file: 'GameHud.cs' }]]);
  assert.equal(systemEvent(notification('Use `List<int>` here.')).detail, 'Use `List<int>` here.');
  assert.deepEqual(systemEvent(notification('All **4** checks pass.')), { kind: 'agent', title: 'Agent "/code-review high" finished', status: 'completed', detail: 'All **4** checks pass.' });
  assert.deepEqual(systemEvent('<command-name>/model</command-name>\n  <command-message>model</command-message>\n  <command-args>sonnet</command-args>'), { kind: 'command', title: '/model sonnet' });
  assert.deepEqual(systemEvent('<command-message>codex:setup</command-message>\n<command-name>/codex:setup</command-name>'), { kind: 'command', title: '/codex:setup' });
  assert.deepEqual(systemEvent('<local-command-stdout>Set model to \x1b[1mopus\x1b[22m</local-command-stdout>'), { kind: 'output', title: 'Set model to opus' });
  assert.equal(systemEvent('<local-command-stdout>Total cost: $0\nDuration: 9s</local-command-stdout>').detail, 'Total cost: $0\nDuration: 9s');
  assert.equal(systemEvent('<local-command-caveat>Caveat: generated by local commands.</local-command-caveat>'), 'skip');
  assert.deepEqual(systemEvent('<relay from="coordinator">\n  <note>New script is ready.</note>\n</relay>', { kind: 'task-notification' }), { kind: 'notice', title: 'New script is ready.', detail: 'New script is ready.' });
  assert.equal(systemEvent('Please review <b>this</b> file', { kind: 'human' }), null);
  assert.equal(systemEvent('Fix the parry window'), null);
});

test('transcripts keep system events out of the user count and report the model', () => {
  const claude = [
    { type: 'user', uuid: 'u1', timestamp: 't1', origin: { kind: 'human' }, message: { content: 'Review the HUD' } },
    { type: 'assistant', uuid: 'a1', timestamp: 't2', message: { id: 'm1', model: 'claude-opus-5-5-20261001', content: [{ type: 'text', text: 'Started a review.' }] } },
    { type: 'user', uuid: 'u2', timestamp: 't3', origin: { kind: 'task-notification' }, message: { content: notification('Nothing found.') } },
    { type: 'user', uuid: 'u3', timestamp: 't4', message: { content: '<local-command-caveat>Caveat</local-command-caveat>' } },
    { type: 'user', uuid: 'u4', timestamp: 't5', message: { content: '<local-command-stdout>Set model to \x1b[1msonnet\x1b[22m and saved</local-command-stdout>' } },
  ];
  const messages = transcriptMessages(claude, 'claude');
  assert.deepEqual(messages.map(item => [item.role, item.text]), [['user', 'Review the HUD'], ['assistant', 'Started a review.'], ['system', 'Agent "/code-review high" finished'], ['system', 'Set model to sonnet and saved']]);
  assert.equal(messages[2].event.detail, 'Nothing found.');
  assert.equal(transcriptModel(claude, 'claude'), 'sonnet');
  assert.equal(transcriptModel(claude.slice(0, 3), 'claude'), 'claude-opus-5-5-20261001');

  const codex = [
    { type: 'turn_context', payload: { model: 'gpt-6-astra' } },
    { type: 'event_msg', timestamp: 't1', payload: { type: 'user_message', message: '<command-name>/caveman</command-name>' } },
    { type: 'event_msg', timestamp: 't2', payload: { type: 'user_message', message: 'Go on' } },
    { type: 'turn_context', payload: { model: 'gpt-6.1-sol' } },
  ];
  assert.deepEqual(transcriptMessages(codex, 'codex').map(item => item.role), ['system', 'user']);
  assert.equal(transcriptModel(codex, 'codex'), 'gpt-6.1-sol');
});
